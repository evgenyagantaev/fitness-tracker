# how the engine should see the word (respelling).  The written form stays in LEX keys.
SPEAK = {
    'темп':'т+эмп',
    'каденс':'кад+энс',   # harden д; stress on е/э (кадЕнс)
}
import re
def stress(text):
    def rep(m):
        w=m.group(0); lw=w.lower()
        if lw not in LEX: raise KeyError(lw)
        s=SPEAK.get(lw, LEX[lw])
        return s.capitalize() if w[0].isupper() else s
    return re.sub(r'[А-Яа-яЁё]+',rep,text)
